// Writes renderer/car-bounds.js: pixel size and visible outline (alpha > 100, the same rule the
// app uses) of every built-in car view. With these the app does not need to decode and scan the
// car images before the editor opens. Run after changing car images (build-car-assets does).
const sharp = require('sharp'),
  path = require('node:path'),
  fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const DM = require('../renderer/model.js');

const file = (body, view) => (body === 'gt' ? `assets/car-${view}.png` : `assets/cars/${body}-${view}.webp`);

async function measure(relative) {
  const { data, info } = await sharp(path.join(root, relative))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let x0 = info.width,
    y0 = info.height,
    x1 = 0,
    y1 = 0;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++)
      if (data[(y * info.width + x) * 4 + 3] > 100) {
        x0 = Math.min(x0, x);
        x1 = Math.max(x1, x);
        y0 = Math.min(y0, y);
        y1 = Math.max(y1, y);
      }
  return { width: info.width, height: info.height, bounds: { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1 } };
}
async function carBounds() {
  const out = {};
  for (const body of Object.keys(DM.CAR_BODIES)) {
    out[body] = {};
    for (const view of ['side', 'top']) out[body][view] = await measure(file(body, view));
  }
  return out;
}
const source = bounds =>
  '// Generated by scripts/build-car-bounds.cjs from the car images. Do not edit by hand.\n' +
  'globalThis.CAR_BOUNDS = ' +
  JSON.stringify(bounds, null, 2) +
  ';\n';
module.exports = { carBounds, source, file };
if (require.main === module)
  carBounds()
    .then(bounds => {
      fs.writeFileSync(path.join(root, 'renderer/car-bounds.js'), source(bounds));
      console.log('renderer/car-bounds.js: ' + Object.keys(bounds).length + ' cars');
    })
    .catch(e => {
      console.error(e);
      process.exitCode = 1;
    });
